'use strict';

const fs = require('fs');
const path = require('path');
const directory = path.join(__dirname, '..', 'src', 'inject');
// 沙箱 preload 只能 require Electron 内置模块；在构建时合并本地模块。
const result = ['// Generated by scripts/build-preload.js. Edit the source modules instead.\n'];
result.push(fs.readFileSync(path.join(directory, 'im-rendered.js'), 'utf8').replace('module.exports = readRenderedIM;', ''));
for (const name of ['im-preload.js', 'page-actions.js', 'task-runner.js']) {
  result.push(`\n// ${name}\n(() => {\n${fs.readFileSync(path.join(directory, name), 'utf8')}\n})();\n`);
}
fs.writeFileSync(path.join(directory, 'im-bundle.js'), result.join(''), 'utf8');
const bridge = fs.readFileSync(path.join(directory, 'platform-form.js'), 'utf8').replace('module.exports = platformFormBridge;', '');
fs.writeFileSync(path.join(directory, 'product-bundle.js'), '// Generated by scripts/build-preload.js\n' + bridge + '\n' + fs.readFileSync(path.join(directory, 'product-scan.js'), 'utf8'), 'utf8');
